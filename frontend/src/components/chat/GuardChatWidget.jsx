import { useState, useEffect, useRef, useCallback, useMemo } from 'react';
import {
  MessageSquare,
  X,
  Search,
  ArrowLeft,
  Send,
  Shield,
  Check,
  CheckCheck,
  Building2,
  Clock,
  User,
} from 'lucide-react';
import { useAuth } from '../../context/AuthContext';
import { useStompSubscription } from '../../hooks/useStompSubscription';
import {
  getGuardsForChat,
  getConversationMessages,
  sendChatMessage,
  markChatConversationAsRead,
  getUnreadChatCount,
} from '../../services/guardChatService';
import '../../styles/GuardChatWidget.css';

export default function GuardChatWidget() {
  const { user } = useAuth();
  const [isOpen, setIsOpen] = useState(false);
  const [guards, setGuards] = useState([]);
  const [isLoadingGuards, setIsLoadingGuards] = useState(false);
  const [unreadTotal, setUnreadTotal] = useState(0);

  // Filters
  const [onDutyOnly, setOnDutyOnly] = useState(false);
  const [searchKeyword, setSearchKeyword] = useState('');

  // Active 1-on-1 conversation
  const [activePeer, setActivePeer] = useState(null);
  const [messages, setMessages] = useState([]);
  const [isLoadingMessages, setIsLoadingMessages] = useState(false);
  const [isSending, setIsSending] = useState(false);
  const [inputText, setInputText] = useState('');

  const messagesEndRef = useRef(null);

  // Load guards list
  const fetchGuards = useCallback(async () => {
    setIsLoadingGuards(true);
    try {
      const data = await getGuardsForChat();
      if (Array.isArray(data)) {
        setGuards(data);
        const total = data.reduce((sum, g) => sum + (g.unreadCount || 0), 0);
        setUnreadTotal(total);
      }
    } catch (err) {
      console.error('Lỗi tải danh sách bảo vệ:', err);
    } finally {
      setIsLoadingGuards(false);
    }
  }, []);

  // Load initial unread count
  useEffect(() => {
    if (!user?.id) return;
    getUnreadChatCount()
      .then((count) => {
        if (typeof count === 'number') setUnreadTotal(count);
      })
      .catch(() => {});
  }, [user?.id]);

  // When widget is opened, refresh guard list
  useEffect(() => {
    if (isOpen) {
      fetchGuards();
    }
  }, [isOpen, fetchGuards]);

  // Scroll messages to bottom
  const scrollToBottom = (behavior = 'smooth') => {
    messagesEndRef.current?.scrollIntoView({ behavior });
  };

  // Open 1-on-1 conversation with a guard
  const handleOpenConversation = async (peer) => {
    setActivePeer(peer);
    setIsLoadingMessages(true);
    try {
      const msgs = await getConversationMessages(peer.id, 60);
      setMessages(Array.isArray(msgs) ? msgs : []);
      // Mark read
      await markChatConversationAsRead(peer.id);
      // Reset unread count for this peer in state
      setGuards((prev) =>
        prev.map((g) => (g.id === peer.id ? { ...g, unreadCount: 0 } : g))
      );
      setUnreadTotal((prev) => Math.max(0, prev - (peer.unreadCount || 0)));
      setTimeout(() => scrollToBottom('auto'), 50);
    } catch (err) {
      console.error('Lỗi tải tin nhắn hội thoại:', err);
    } finally {
      setIsLoadingMessages(false);
    }
  };

  // Close active conversation back to guard list
  const handleBackToList = () => {
    setActivePeer(null);
    setMessages([]);
    fetchGuards();
  };

  // Send message
  const handleSendMessage = async (e) => {
    e?.preventDefault();
    if (!inputText.trim() || !activePeer || isSending) return;

    const content = inputText.trim();
    setInputText('');
    setIsSending(true);

    try {
      const sent = await sendChatMessage(activePeer.id, content);
      setMessages((prev) => [...prev, sent]);
      // Update last message in guard list
      setGuards((prev) =>
        prev.map((g) =>
          g.id === activePeer.id
            ? { ...g, lastMessage: content, lastMessageAt: sent.createdAt }
            : g
        )
      );
      setTimeout(() => scrollToBottom('smooth'), 50);
    } catch (err) {
      console.error('Lỗi gửi tin nhắn:', err);
    } finally {
      setIsSending(false);
    }
  };

  // Real-time STOMP message handler
  const handleIncomingMessage = useCallback(
    (msg) => {
      if (!msg) return;

      const currentPeerId = activePeer?.id;
      // If we are currently chatting with the sender or receiver
      if (
        currentPeerId &&
        (msg.senderId === currentPeerId || msg.receiverId === currentPeerId)
      ) {
        setMessages((prev) => {
          if (prev.some((m) => m.id && msg.id && m.id === msg.id)) return prev;
          return [...prev, msg];
        });
        if (msg.senderId === currentPeerId) {
          markChatConversationAsRead(currentPeerId).catch(() => {});
        }
        setTimeout(() => scrollToBottom('smooth'), 60);
      } else {
        // Someone else messaged me
        if (msg.receiverId === user?.id) {
          setUnreadTotal((prev) => prev + 1);
          setGuards((prev) =>
            prev.map((g) => {
              if (g.id === msg.senderId) {
                return {
                  ...g,
                  unreadCount: (g.unreadCount || 0) + 1,
                  lastMessage: msg.content,
                  lastMessageAt: msg.createdAt,
                };
              }
              return g;
            })
          );
        }
      }

      // Update preview in list
      const peerId = msg.senderId === user?.id ? msg.receiverId : msg.senderId;
      setGuards((prev) =>
        prev.map((g) =>
          g.id === peerId
            ? { ...g, lastMessage: msg.content, lastMessageAt: msg.createdAt }
            : g
        )
      );
    },
    [activePeer?.id, user?.id]
  );

  // Subscribe to personal guard chat topic
  const chatTopic = user?.id ? `/topic/guards/${user.id}/messages` : null;
  useStompSubscription(chatTopic, handleIncomingMessage);

  // Filtered guard list
  const filteredGuards = useMemo(() => {
    return guards.filter((g) => {
      if (onDutyOnly && !g.onDuty) return false;
      if (searchKeyword.trim()) {
        const q = searchKeyword.trim().toLowerCase();
        const matchName = g.fullName?.toLowerCase().includes(q);
        const matchCode = g.userCode?.toLowerCase().includes(q);
        const matchShift = g.currentShiftName?.toLowerCase().includes(q);
        const matchBldg = g.assignedBuilding?.toLowerCase().includes(q);
        if (!matchName && !matchCode && !matchShift && !matchBldg) return false;
      }
      return true;
    });
  }, [guards, onDutyOnly, searchKeyword]);

  const onDutyCount = useMemo(() => guards.filter((g) => g.onDuty).length, [guards]);

  return (
    <>
      {/* Floating Action Button */}
      <button
        type="button"
        className="guard-chat-fab"
        onClick={() => setIsOpen((prev) => !prev)}
        aria-label="Nhắn tin nội bộ bảo vệ"
        title="Nhắn tin nội bộ bảo vệ"
      >
        <MessageSquare size={24} />
        {unreadTotal > 0 && (
          <span className="guard-chat-badge">
            {unreadTotal > 99 ? '99+' : unreadTotal}
          </span>
        )}
      </button>

      {/* Chat Popover Window */}
      {isOpen && (
        <div className="guard-chat-window">
          {/* View 1: Guard Directory */}
          {!activePeer ? (
            <>
              {/* Header */}
              <div className="guard-chat-header">
                <div>
                  <div className="guard-chat-header-title">
                    <Shield size={18} className="text-teal-600 dark:text-teal-400" />
                    <span>Tin nhắn Bảo vệ</span>
                  </div>
                  <div className="guard-chat-header-sub">
                    {guards.length} nhân sự · {onDutyCount} đang trong ca trực
                  </div>
                </div>
                <button
                  type="button"
                  className="guard-chat-icon-btn"
                  onClick={() => setIsOpen(false)}
                  title="Đóng"
                >
                  <X size={18} />
                </button>
              </div>

              {/* Filter Tabs: All vs On-Duty this shift */}
              <div className="guard-chat-filter-bar">
                <button
                  type="button"
                  className={`guard-chat-filter-btn ${!onDutyOnly ? 'active' : ''}`}
                  onClick={() => setOnDutyOnly(false)}
                >
                  Tất cả ({guards.length})
                </button>
                <button
                  type="button"
                  className={`guard-chat-filter-btn ${onDutyOnly ? 'active' : ''}`}
                  onClick={() => setOnDutyOnly(true)}
                >
                  <span className="guard-chat-dot" />
                  Đang trong ca ({onDutyCount})
                </button>
              </div>

              {/* Search */}
              <div className="guard-chat-search-wrap">
                <Search size={15} className="guard-chat-search-icon" />
                <input
                  type="text"
                  className="guard-chat-search-input"
                  placeholder="Tìm theo tên, mã số, ca trực..."
                  value={searchKeyword}
                  onChange={(e) => setSearchKeyword(e.target.value)}
                />
                {searchKeyword && (
                  <button
                    type="button"
                    className="guard-chat-search-clear"
                    onClick={() => setSearchKeyword('')}
                  >
                    <X size={14} />
                  </button>
                )}
              </div>

              {/* Guard List */}
              <div className="guard-chat-list">
                {isLoadingGuards ? (
                  <div className="p-8 text-center text-sm text-slate-500">
                    Đang tải danh sách bảo vệ...
                  </div>
                ) : filteredGuards.length === 0 ? (
                  <div className="p-8 text-center text-sm text-slate-500">
                    {onDutyOnly
                      ? 'Không có bảo vệ nào đang trong ca trực'
                      : 'Không tìm thấy bảo vệ nào phù hợp'}
                  </div>
                ) : (
                  filteredGuards.map((guard) => (
                    <div
                      key={guard.id}
                      className="guard-chat-item"
                      onClick={() => handleOpenConversation(guard)}
                    >
                      <div className="guard-chat-avatar-wrap">
                        {guard.avatarUrl ? (
                          <img
                            src={guard.avatarUrl}
                            alt={guard.fullName}
                            className="guard-chat-avatar"
                          />
                        ) : (
                          <div className="guard-chat-avatar">
                            {guard.fullName?.[0]?.toUpperCase() || 'B'}
                          </div>
                        )}
                        <span
                          className={`guard-chat-status-dot ${
                            guard.onDuty ? 'online' : 'offline'
                          }`}
                        />
                      </div>

                      <div className="guard-chat-item-info">
                        <div className="guard-chat-item-top">
                          <span className="guard-chat-item-name">
                            {guard.fullName}
                          </span>
                          {guard.lastMessageAt && (
                            <span className="guard-chat-item-time">
                              {new Date(guard.lastMessageAt).toLocaleTimeString(
                                'vi-VN',
                                { hour: '2-digit', minute: '2-digit' }
                              )}
                            </span>
                          )}
                        </div>

                        <div className="guard-chat-item-sub">
                          {guard.onDuty ? (
                            <span className="guard-chat-tag-onduty">
                              {guard.currentShiftName
                                ? `Ca: ${guard.currentShiftName}`
                                : 'Đang trực'}
                            </span>
                          ) : (
                            <span className="guard-chat-tag-offduty">Ngoài ca</span>
                          )}
                          {guard.assignedBuilding && (
                            <span className="text-slate-500 text-xs truncate">
                              • {guard.assignedBuilding}
                            </span>
                          )}
                        </div>

                        {guard.lastMessage && (
                          <div className="guard-chat-preview-text">
                            {guard.lastMessage}
                          </div>
                        )}
                      </div>

                      {guard.unreadCount > 0 && (
                        <span className="guard-chat-badge relative top-auto right-auto shrink-0">
                          {guard.unreadCount}
                        </span>
                      )}
                    </div>
                  ))
                )}
              </div>
            </>
          ) : (
            /* View 2: Active 1-on-1 Conversation */
            <div className="guard-chat-conversation">
              {/* Conversation Header */}
              <div className="guard-chat-header">
                <div className="flex items-center gap-2 min-w-0">
                  <button
                    type="button"
                    className="guard-chat-icon-btn"
                    onClick={handleBackToList}
                    title="Quay lại danh sách"
                  >
                    <ArrowLeft size={18} />
                  </button>
                  <div className="guard-chat-avatar-wrap !w-8 !h-8">
                    {activePeer.avatarUrl ? (
                      <img
                        src={activePeer.avatarUrl}
                        alt={activePeer.fullName}
                        className="guard-chat-avatar"
                      />
                    ) : (
                      <div className="guard-chat-avatar !text-xs">
                        {activePeer.fullName?.[0]?.toUpperCase() || 'B'}
                      </div>
                    )}
                    <span
                      className={`guard-chat-status-dot ${
                        activePeer.onDuty ? 'online' : 'offline'
                      }`}
                    />
                  </div>
                  <div className="min-w-0">
                    <div className="guard-chat-item-name !text-sm">
                      {activePeer.fullName}
                    </div>
                    <div className="text-[11px] text-slate-500 truncate">
                      {activePeer.onDuty
                        ? `Đang trực ${activePeer.currentShiftName ? `(${activePeer.currentShiftName})` : ''} • ${activePeer.assignedBuilding || 'Toàn trường'}`
                        : 'Ngoài ca trực'}
                    </div>
                  </div>
                </div>

                <button
                  type="button"
                  className="guard-chat-icon-btn"
                  onClick={() => setIsOpen(false)}
                  title="Đóng"
                >
                  <X size={18} />
                </button>
              </div>

              {/* Message List */}
              <div className="guard-chat-conversation-body">
                {isLoadingMessages ? (
                  <div className="m-auto text-center text-sm text-slate-500">
                    Đang tải cuộc trò chuyện...
                  </div>
                ) : messages.length === 0 ? (
                  <div className="m-auto text-center p-6 text-slate-500">
                    <MessageSquare
                      size={36}
                      className="mx-auto mb-2 text-slate-400 opacity-60"
                    />
                    <div className="text-sm font-semibold">Chưa có tin nhắn</div>
                    <div className="text-xs text-slate-400 mt-1">
                      Gửi tin nhắn để bắt đầu trao đổi với {activePeer.fullName}
                    </div>
                  </div>
                ) : (
                  messages.map((m) => {
                    const isMe = m.senderId === user?.id;
                    const timeStr = m.createdAt
                      ? new Date(m.createdAt).toLocaleTimeString('vi-VN', {
                          hour: '2-digit',
                          minute: '2-digit',
                        })
                      : '';

                    return (
                      <div
                        key={m.id || Math.random()}
                        className={`guard-chat-bubble-wrap ${isMe ? 'me' : 'peer'}`}
                      >
                        <div className="guard-chat-bubble">{m.content}</div>
                        <div className="guard-chat-meta">
                          <span>{timeStr}</span>
                          {isMe && (
                            <span>
                              {m.isRead ? (
                                <CheckCheck size={12} className="text-teal-400" />
                              ) : (
                                <Check size={12} />
                              )}
                            </span>
                          )}
                        </div>
                      </div>
                    );
                  })
                )}
                <div ref={messagesEndRef} />
              </div>

              {/* Message Input Box */}
              <form className="guard-chat-input-box" onSubmit={handleSendMessage}>
                <textarea
                  className="guard-chat-textarea"
                  placeholder={`Nhập tin nhắn cho ${activePeer.fullName}...`}
                  rows={1}
                  value={inputText}
                  onChange={(e) => setInputText(e.target.value)}
                  onKeyDown={(e) => {
                    if (e.key === 'Enter' && !e.shiftKey) {
                      e.preventDefault();
                      handleSendMessage();
                    }
                  }}
                />
                <button
                  type="submit"
                  className="guard-chat-send-btn"
                  disabled={!inputText.trim() || isSending}
                  title="Gửi tin nhắn"
                >
                  <Send size={15} />
                </button>
              </form>
            </div>
          )}
        </div>
      )}
    </>
  );
}

